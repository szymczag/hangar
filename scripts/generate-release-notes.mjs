// Bundles the current release's headlines into the app so the "about this
// build" dialog can show what changed without asking anything off-instance.
//
// Usage: node scripts/generate-release-notes.mjs [--check]
// Reads:  docs/releases/hangar-v<version>.md  (highest version present)
//         UPSTREAM_BASE.json  (which upstream revision this fork is built on)
// Writes: apps/web/ce/components/license/release-notes.generated.ts

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("../", import.meta.url));
const notesDirectory = path.join(repoRoot, "docs/releases");
const outputPath = path.join(repoRoot, "apps/web/ce/components/license/release-notes.generated.ts");

// A dialog, not a changelog. Past this many the reader stops reading.
const MAX_HIGHLIGHTS = 5;

const HEADER = `// Copyright (c) 2026-present Maciej Szymczak and contributors
// SPDX-License-Identifier: AGPL-3.0-only

// Generated by scripts/generate-release-notes.mjs from docs/releases/.
// Do not edit; run \`pnpm generate:release-notes\`.`;

/** Split "0.1.0-rc.40" into comparable parts, numbers staying numbers. */
function versionParts(value) {
  return value.split(/[.-]/).map((part) => (/^\d+$/.test(part) ? Number(part) : part));
}

/** Sort "0.1.0-rc.40" style versions numerically rather than lexically. */
function compareVersions(a, b) {
  const left = versionParts(a);
  const right = versionParts(b);

  for (let i = 0; i < Math.max(left.length, right.length); i++) {
    const l = left[i];
    const r = right[i];
    if (l === r) continue;
    if (l === undefined) return -1;
    if (r === undefined) return 1;
    if (typeof l === "number" && typeof r === "number") return l - r;
    return String(l).localeCompare(String(r));
  }
  return 0;
}

export function latestReleaseNotes(directory = notesDirectory) {
  const versions = readdirSync(directory)
    .map((name) => /^hangar-v(.+)\.md$/.exec(name))
    .filter(Boolean)
    .map((match) => match[1])
    .toSorted(compareVersions);

  const version = versions.at(-1);
  if (!version) return { version: "", highlights: [] };

  const markdown = readFileSync(path.join(directory, `hangar-v${version}.md`), "utf8");

  // The curated notes lead each item with a bold sentence stating what changed;
  // the paragraph after it is the reasoning, which a dialog has no room for.
  const section = markdown.split(/^## /m).find((block) => block.startsWith("Security and privacy")) ?? "";
  const highlights = [...section.matchAll(/^\*\*(.+?)\*\*/gm)]
    .map((match) => match[1].replace(/\s+/g, " ").trim())
    .slice(0, MAX_HIGHLIGHTS);

  return { version, highlights };
}

/** Which upstream revision this fork is built on. Lives at the repo root, outside every app's Vite root. */
export function upstreamBase(root = repoRoot) {
  try {
    const base = JSON.parse(readFileSync(path.join(root, "UPSTREAM_BASE.json"), "utf8"));
    return { version: String(base.package_version ?? ""), revision: String(base.revision ?? "").slice(0, 8) };
  } catch {
    return { version: "", revision: "" };
  }
}

/**
 * Serialize in the house format rather than with `JSON.stringify`, whose quoted
 * keys and missing trailing commas oxfmt rewrites -- which would make the
 * committed file permanently disagree with what `--check` renders.
 */
function literal(value, indent = "") {
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return `[\n${value.map((item) => `${inner}${literal(item, inner)},\n`).join("")}${indent}]`;
  }
  if (value && typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) return "{}";
    return `{\n${entries.map(([key, item]) => `${inner}${key}: ${literal(item, inner)},\n`).join("")}${indent}}`;
  }
  return JSON.stringify(value);
}

function render(payload) {
  return `${HEADER}

export type TBuildIdentity = {
  version: string;
  highlights: string[];
  upstream: { version: string; revision: string };
};

export const RELEASE_NOTES: TBuildIdentity = ${literal(payload)};
`;
}

function main() {
  const contents = render({ ...latestReleaseNotes(), upstream: upstreamBase() });

  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(outputPath, "utf8");
    } catch {
      current = "";
    }
    if (current !== contents) {
      console.error("Release notes are stale. Run `pnpm generate:release-notes`.");
      process.exit(1);
    }
    console.log("Release notes are up to date.");
    return;
  }

  writeFileSync(outputPath, contents, "utf8");
  console.log(`Wrote ${path.relative(repoRoot, outputPath)}`);
}

if (fileURLToPath(import.meta.url) === process.argv[1]) main();
