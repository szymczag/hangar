// Writes the nginx security-header template for a static single-page build.
//
//   hangar-csp-nginx --html build/client/index.html --out build/csp/security-headers.conf.template
//
// Inline scripts are hashed from the built index.html, so the policy always
// matches the build it ships with. Origins only known where the image runs
// are left as ${HANGAR_CSP_*} placeholders for the nginx image's envsubst.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { parseArgs } from "node:util";

import { RUNTIME_STYLE_ELEMENTS, buildContentSecurityPolicy, hashSource, inlineScriptHashes } from "../src/index.mjs";

const { values } = parseArgs({
  options: {
    html: { type: "string" },
    out: { type: "string" },
  },
});

if (!values.html || !values.out) {
  console.error("usage: hangar-csp-nginx --html <index.html> --out <template>");
  process.exit(2);
}

const scriptSources = inlineScriptHashes(readFileSync(values.html, "utf8"));
if (scriptSources.length === 0) {
  // React Router always inlines its context and module loader; finding none
  // means the HTML is not the build output this was meant for.
  console.error(`hangar-csp-nginx: no inline scripts found in ${values.html}`);
  process.exit(1);
}

const policy = buildContentSecurityPolicy({
  scriptSources,
  styleElementSources: RUNTIME_STYLE_ELEMENTS.map(hashSource),
  imgSrc: "${HANGAR_CSP_IMG_SRC}",
  connectSrc: "${HANGAR_CSP_CONNECT_SRC}",
  mediaSrc: "${HANGAR_CSP_MEDIA_SRC}",
  frameSrc: "${HANGAR_CSP_FRAME_SRC}",
  formAction: "${HANGAR_CSP_FORM_ACTION}",
  frameAncestors: "'none'",
});

const template = `# Generated by @plane/csp from ${values.html} at build time. Do not edit.
# Included in every server and location block that sets headers: nginx drops
# inherited add_header directives in a block that has its own.
add_header X-Frame-Options "DENY" always;
add_header X-Content-Type-Options "nosniff" always;
add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;
add_header Referrer-Policy "strict-origin-when-cross-origin" always;
add_header X-XSS-Protection "0" always;
add_header \${HANGAR_CSP_HEADER} "${policy}\${HANGAR_CSP_REPORT}" always;
# Trusted Types measurement, always report-only; empty (header omitted) when
# HANGAR_CSP_TRUSTED_TYPES=off.
add_header Content-Security-Policy-Report-Only "\${HANGAR_CSP_TRUSTED_TYPES_POLICY}" always;
`;

mkdirSync(dirname(values.out), { recursive: true });
writeFileSync(values.out, template);
console.log(`hangar-csp-nginx: ${scriptSources.length} inline script hash(es) -> ${values.out}`);
